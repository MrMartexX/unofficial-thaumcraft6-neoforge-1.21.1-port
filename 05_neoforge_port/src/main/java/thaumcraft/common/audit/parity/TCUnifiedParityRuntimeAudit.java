    public static Report writeMarkdown(Path output, MinecraftServer server) throws IOException {
        Files.createDirectories(output.toAbsolutePath().normalize().getParent());
        Report report = run(server);

        ArrayList<String> lines = new ArrayList<>();
        lines.add("# Thaumcraft 6 Runtime Behavioral Parity Audit");
        lines.add("");
        lines.add("Generated by TCUnifiedParityRuntimeAudit on server startup.");
        lines.add("");
        lines.add("## Summary");
        lines.add("");
        lines.add("| Category | Total | Passed | Failed | Status |");
        lines.add("|---|---:|---:|---:|---|");
        lines.add(categoryRow("Core Machinery & BlockEntities", report.machineryChecks()));
        lines.add(categoryRow("Essentia Transport & Capabilities", report.transportChecks()));
        lines.add(categoryRow("Aura & Environmental Energy", report.auraChecks()));
        lines.add(categoryRow("Crafting, Recipes & Containers", report.craftingChecks()));
        lines.add(categoryRow("Equipment, Armor & Mobility", report.equipmentChecks()));
        lines.add(categoryRow("Multiblock Structure Blueprints", report.multiblockChecks()));
        lines.add(categoryRow("Research & Discovery Flow", report.researchChecks()));
        lines.add(categoryRow("Worldgen, Biomes & Structures", report.worldgenChecks()));
        lines.add("");
        lines.add("### Overall: " + report.passed() + " / " + report.checks().size()
                + " checks passed (" + String.format(Locale.ROOT, "%.1f", report.percent()) + "%).");
        lines.add("");
        lines.add("## Detailed Audit Checks");
        lines.add("");
        lines.add("| Subsystem | Name | Result | Legacy Contract & Notes |");
        lines.add("|---|---|---|---|");
        for (Check check : report.checks()) {
            lines.add("| " + check.subsystem() + " | " + check.name() + " | "
                    + (check.passed() ? "PASS" : "**FAIL**") + " | "
                    + check.notes().replace("|", "\\|") + " |");
        }
        lines.add("");
        lines.add("## Known Parity Violations & Required Actions");
        lines.add("");
        List<Check> failed = report.checks().stream().filter(c -> !c.passed()).toList();
        if (failed.isEmpty()) {
            lines.add("All evaluated runtime contracts strictly conform to Legacy Thaumcraft 6.");
        } else {
            for (Check f : failed) {
                lines.add("- **[" + f.subsystem() + "] " + f.name() + "**: " + f.notes());
            }
        }

        Files.write(output, lines);
        return report;
    }

    private static String categoryRow(String name, List<Check> checks) {
        int passed = (int) checks.stream().filter(Check::passed).count();
        int total = checks.size();
        int failed = total - passed;
        String status = failed == 0 ? "OK" : "**DISCREPANCY** (" + failed + ")";
        return "| " + name + " | " + total + " | " + passed + " | " + failed + " | " + status + " |";
    }

    public static Report run(MinecraftServer server) {
        ArrayList<Check> checks = new ArrayList<>();
        ServerLevel level = server == null ? null : server.overworld();
        ServerPlayer player = level == null ? null : FakePlayerFactory.getMinecraft(level);

        checks.addAll(auditMachinery(server, level));
        checks.addAll(auditTransport(level));
        checks.addAll(auditAura(level, player));
        checks.addAll(auditCrafting(server, player));
        checks.addAll(auditEquipment(player));
        checks.addAll(auditMultiblocks(level));
        checks.addAll(auditResearch(player));
        checks.addAll(auditWorldgen(level));

        return new Report(List.copyOf(checks));
    }

    private static List<Check> auditMachinery(MinecraftServer server, ServerLevel level) {
        ArrayList<Check> checks = new ArrayList<>();
        checks.add(new Check("Machinery", "arcane_workbench_entity_registered",
                TCBlocks.ARCANE_WORKBENCH.get() instanceof TCArcaneWorkbenchBlock,
                "Arcane Workbench is custom TCArcaneWorkbenchBlock instance"));
        checks.add(new Check("Machinery", "research_table_entity_registered",
                TCBlocks.RESEARCH_TABLE.get() instanceof TCResearchTableBlock,
                "Research Table is custom TCResearchTableBlock instance"));
        checks.add(new Check("Machinery", "crucible_entity_registered",
                TCBlocks.CRUCIBLE.get() instanceof TCCrucibleBlock,
                "Crucible is custom TCCrucibleBlock instance"));
        checks.add(new Check("Machinery", "infusion_matrix_entity_registered",
                TCBlocks.INFUSION_MATRIX.get() instanceof TCInfusionMatrixBlock,
                "Infusion Matrix is custom TCInfusionMatrixBlock instance"));
        checks.add(new Check("Machinery", "centrifuge_entity_registered",
                TCBlocks.CENTRIFUGE.get() instanceof TCCentrifugeBlock,
                "Centrifuge is custom TCCentrifugeBlock instance"));
        checks.add(new Check("Machinery", "brain_jar_entity_registered",
                TCBlocks.JAR_BRAIN.get() instanceof TCBrainJarBlock,
                "Brain in a Jar is custom TCBrainJarBlock instance"));

        if (level != null) {
            BlockPos pos = new BlockPos(0, 200, 0);
            TCCentrifugeBlockEntity centrifuge = new TCCentrifugeBlockEntity(pos, TCBlocks.CENTRIFUGE.get().defaultBlockState());
            int added = centrifuge.addEssentia("lux", 1, net.minecraft.core.Direction.DOWN, false);
            boolean accepted = added == 1 && centrifuge.aspectIn == thaumcraft.api.aspects.Aspect.LIGHT && centrifuge.getProcess() == 39;
            centrifuge.setProcessForTesting(0);
            centrifuge.processEssentiaForTesting();
            boolean split = centrifuge.aspectIn == null && centrifuge.aspectOut != null
                    && (centrifuge.aspectOut == thaumcraft.api.aspects.Aspect.AIR || centrifuge.aspectOut == thaumcraft.api.aspects.Aspect.FIRE);
            checks.add(new Check("Machinery", "centrifuge_process_delay_contract",
                    accepted && split,
                    "Centrifuge implements 39-tick process delay and aspect splitting"));

            ServerPlayer menuPlayer = FakePlayerFactory.getMinecraft(level);
            var builder = new thaumcraft.common.tiles.crafting.TCGolemBuilderBlockEntity(pos, TCBlocks.GOLEM_BUILDER.get().defaultBlockState());
            var clientBuilderMenu = new thaumcraft.common.menu.TCGolemBuilderMenu(0, menuPlayer.getInventory());
            var serverBuilderData = builder.dataAccessForTesting();
            long[] testMasks = { -1L, 0x1234_89AB_CDEF_5678L };
            boolean builderRoundTripOk = serverBuilderData.getCount() == 6;
            for (long mask : testMasks) {
                builder.setGolemForTesting(mask);
                for (int slotIdx = 0; slotIdx < serverBuilderData.getCount(); slotIdx++) {
                    clientBuilderMenu.setData(slotIdx, (short) serverBuilderData.get(slotIdx));
                }
                if (clientBuilderMenu.getGolemProps() != mask) {
                    builderRoundTripOk = false;
                }
            }
            checks.add(new Check("Machinery", "golem_builder_64bit_container_data_round_trip",
                    builderRoundTripOk,
                    "TCGolemBuilderMenu round-trips full 64-bit golem properties across 16-bit signed ContainerData slots"));
        }
        return checks;
    }

