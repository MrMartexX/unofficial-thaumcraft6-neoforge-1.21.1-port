    public record Report(List<Check> checks) {
        public int passed() {
            return (int) checks.stream().filter(Check::passed).count();
        }

        public int failed() {
            return checks.size() - passed();
        }

        public double percent() {
            return checks.isEmpty() ? 0.0 : (passed() * 100.0) / checks.size();
        }

        public List<Check> machineryChecks() {
            return checks.stream().filter(c -> "Machinery".equals(c.subsystem())).toList();
        }

        public List<Check> transportChecks() {
            return checks.stream().filter(c -> "Transport".equals(c.subsystem())).toList();
        }

        public List<Check> auraChecks() {
            return checks.stream().filter(c -> "Aura".equals(c.subsystem())).toList();
        }

        public List<Check> craftingChecks() {
            return checks.stream().filter(c -> "Crafting".equals(c.subsystem())).toList();
        }

        public List<Check> equipmentChecks() {
            return checks.stream().filter(c -> "Equipment".equals(c.subsystem())).toList();
        }

        public List<Check> multiblockChecks() {
            return checks.stream().filter(c -> "Multiblocks".equals(c.subsystem())).toList();
        }

        public List<Check> researchChecks() {
            return checks.stream().filter(c -> "Research".equals(c.subsystem())).toList();
        }
    }

    public record Check(String subsystem, String name, boolean passed, String notes) {
    }
