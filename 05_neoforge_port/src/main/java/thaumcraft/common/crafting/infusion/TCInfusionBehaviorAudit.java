public final class TCInfusionBehaviorAudit {
    private static final ResourceLocation CLOUD_RING = ResourceLocation.fromNamespaceAndPath(Thaumcraft.MODID, "cloudring");

    private TCInfusionBehaviorAudit() {
    }

    public static Report writeMarkdown(Path output, MinecraftServer server) throws IOException {
        Files.createDirectories(output.toAbsolutePath().normalize().getParent());
        Report report = run(server);

        ArrayList<String> lines = new ArrayList<>();
        lines.add("# Infusion Behavior Audit");
        lines.add("");
        lines.add("Generated by the NeoForge runtime audit exporter after server recipe reload.");
        lines.add("");
        lines.add("## Summary");
        lines.add("");
        lines.add("| Check | Result |");
        lines.add("|---|---:|");
        lines.add("| Passed | " + report.passed() + " |");
        lines.add("| Failed | " + report.failed() + " |");
        lines.add("| Infusion recipes loaded | " + report.infusionRecipeCount() + " |");
        lines.add("");
        lines.add("## Checks");
        lines.add("");
        lines.add("| Name | Result | Notes |");
        lines.add("|---|---|---|");
        for (Check check : report.checks()) {
            lines.add("| " + check.name() + " | " + (check.passed() ? "PASS" : "FAIL") + " | " + check.notes().replace("|", "\\|") + " |");
        }
        lines.add("");
        lines.add("## Boundary");
        lines.add("");
        lines.add("- This validates the current server-owned infusion input snapshot and recipe matcher boundary.");
        lines.add("- The audit also places a matrix and pedestals in a runtime server world to validate legacy-aligned pedestal discovery.");
        lines.add("- Legacy parity point: component matching uses Forge/NeoForge RecipeMatcher 1:1 semantics, so extra pedestal inputs must fail.");
        lines.add("- This does not implement item consumption, instability events, essentia transport, particles, beams or matrix animation.");

        Files.write(output, lines);
        return report;
    }

    private static Report run(MinecraftServer server) {
        ArrayList<Check> checks = new ArrayList<>();
        RecipeManager recipeManager = server.getRecipeManager();
        List<RecipeHolder<TCInfusionRecipe>> infusionRecipes = recipeManager.getAllRecipesFor(TCRecipes.INFUSION_TYPE.get());
        checks.add(new Check(
                "infusion_recipes_loaded",
                infusionRecipes.size() >= 30,
                "loaded=" + infusionRecipes.size()
        ));

        Optional<RecipeHolder<TCInfusionRecipe>> cloudRingHolder = infusionRecipes.stream()
                .filter(holder -> holder.id().equals(CLOUD_RING))
                .findFirst();
        Optional<TCInfusionRecipe> cloudRing = cloudRingHolder.map(RecipeHolder::value);
        checks.add(new Check(
                "cloudring_recipe_loaded",
                cloudRing.isPresent(),
                "recipe=" + CLOUD_RING
        ));

        if (cloudRing.isPresent()) {
            TCInfusionRecipe recipe = cloudRing.get();
            checks.add(new Check(
                    "cloudring_legacy_recipe_shape",
                    "CLOUDRING".equals(recipe.getResearch())
                            && recipe.instability() == 1
                            && recipe.components().size() == 2
                            && recipe.aspectCosts().size() == 1
                            && recipe.aspectCosts().getFirst().resolvedAspect() == Aspect.AIR
                            && recipe.aspectCosts().getFirst().amount() == 50
                            && recipe.result().is(TCItems.CLOUD_RING.get()),
                    "research=" + recipe.getResearch()
                            + ", instability=" + recipe.instability()
                            + ", components=" + recipe.components().size()
                            + ", aspects=" + recipe.aspectCosts().size()
            ));

            TCInfusionAssembly exactAssembly = TCInfusionAssembly.of(
                    new ItemStack(TCItems.BAUBLE_RING.get()),
                    List.of(
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()),
                            new ItemStack(Items.FEATHER)
                    ),
                    new AspectList().add(Aspect.AIR, 50)
            );
            TCInfusionValidationResult exactResult = exactAssembly.validateAgainst(recipe);
            checks.add(new Check(
                    "cloudring_happy_path_direct_validation",
                    exactResult.valid()
                            && exactResult.remainingAspects().visSize() == 0
                            && exactResult.requiredComponentCount() == 2
                            && exactResult.suppliedComponentCount() == 2,
                    "reason=" + exactResult.reason() + ", remaining=" + exactResult.remainingAspects().visSize()
            ));

            TCInfusionAssembly reversedAssembly = TCInfusionAssembly.of(
                    new ItemStack(TCItems.BAUBLE_RING.get()),
                    List.of(
                            new ItemStack(Items.FEATHER),
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get())
                    ),
                    new AspectList().add(Aspect.AIR, 50)
            );
            checks.add(new Check(
                    "cloudring_unordered_components_match",
                    reversedAssembly.validateAgainst(recipe).valid(),
                    "legacy RecipeMatcher accepts component order changes"
            ));

            TCInfusionAssembly extraComponentAssembly = TCInfusionAssembly.of(
                    new ItemStack(TCItems.BAUBLE_RING.get()),
                    List.of(
                            new ItemStack(Items.FEATHER),
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()),
                            new ItemStack(Items.STICK)
                    ),
                    new AspectList().add(Aspect.AIR, 50)
            );
            TCInfusionValidationResult extraResult = extraComponentAssembly.validateAgainst(recipe);
            checks.add(new Check(
                    "cloudring_extra_component_fails_legacy_one_to_one_match",
                    !extraResult.valid() && "component_mismatch".equals(extraResult.reason()),
                    "reason=" + extraResult.reason()
            ));

            TCInfusionAssembly missingAspectAssembly = TCInfusionAssembly.of(
                    new ItemStack(TCItems.BAUBLE_RING.get()),
                    List.of(
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()),
                            new ItemStack(Items.FEATHER)
                    ),
                    new AspectList().add(Aspect.AIR, 49)
            );
            TCInfusionValidationResult missingAspectResult = missingAspectAssembly.validateAgainst(recipe);
            checks.add(new Check(
                    "cloudring_missing_aspect_fails_before_components",
                    !missingAspectResult.valid() && "missing_aspects".equals(missingAspectResult.reason()),
                    "reason=" + missingAspectResult.reason()
            ));

            TCInfusionAssembly wrongCatalystAssembly = TCInfusionAssembly.of(
                    new ItemStack(Items.IRON_INGOT),
                    List.of(
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()),
                            new ItemStack(Items.FEATHER)
                    ),
                    new AspectList().add(Aspect.AIR, 50)
            );
            TCInfusionValidationResult wrongCatalystResult = wrongCatalystAssembly.validateAgainst(recipe);
            checks.add(new Check(
                    "cloudring_wrong_catalyst_fails",
                    !wrongCatalystResult.valid() && "catalyst_mismatch".equals(wrongCatalystResult.reason()),
                    "reason=" + wrongCatalystResult.reason()
            ));

            TCInfusionAssembly noPlayerAssembly = TCInfusionAssembly.of(
                    new ItemStack(TCItems.BAUBLE_RING.get()),
                    List.of(
                            new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()),
                            new ItemStack(Items.FEATHER)
                    ),
                    new AspectList().add(Aspect.AIR, 50)
            );
            checks.add(new Check(
                    "researched_recipe_lookup_requires_player_context",
                    noPlayerAssembly.findMatchingRecipe(recipeManager, null).isEmpty(),
                    "legacy InfusionRecipe.matches checks player knowledge before recipe match"
            ));

            cloudRingHolder.ifPresent(holder -> addRuntimeMatrixChecks(server, holder, checks));
        }

        return new Report(List.copyOf(checks), infusionRecipes.size());
    }

    private static void addRuntimeMatrixChecks(MinecraftServer server, RecipeHolder<TCInfusionRecipe> cloudRing, ArrayList<Check> checks) {
        ServerLevel level = server.overworld();
        BlockPos matrixPos = new BlockPos(0, level.getMinBuildHeight() + 12, 0);
        BlockPos centerPos = matrixPos.below(2);
        BlockPos featherPos = matrixPos.offset(2, -2, 0);
        BlockPos crystalPos = matrixPos.offset(-2, -2, 0);
        BlockPos extraPos = matrixPos.offset(0, -2, 2);
        BlockPos outOfColumnPos = matrixPos.offset(0, -2, 3);

        clearTestArea(level, matrixPos);
        level.setBlock(matrixPos, TCBlocks.INFUSION_MATRIX.get().defaultBlockState(), 3);
        level.setBlock(centerPos, TCBlocks.ARCANE_PEDESTAL.get().defaultBlockState(), 3);
        level.setBlock(featherPos, TCBlocks.ARCANE_PEDESTAL.get().defaultBlockState(), 3);
        level.setBlock(crystalPos, TCBlocks.ARCANE_PEDESTAL.get().defaultBlockState(), 3);
        level.setBlock(outOfColumnPos, TCBlocks.ARCANE_PEDESTAL.get().defaultBlockState(), 3);

        TCInfusionMatrixBlockEntity matrix = blockEntity(level, matrixPos, TCInfusionMatrixBlockEntity.class);
        TCInfusionPedestalBlockEntity center = blockEntity(level, centerPos, TCInfusionPedestalBlockEntity.class);
        TCInfusionPedestalBlockEntity feather = blockEntity(level, featherPos, TCInfusionPedestalBlockEntity.class);
        TCInfusionPedestalBlockEntity crystal = blockEntity(level, crystalPos, TCInfusionPedestalBlockEntity.class);
        TCInfusionPedestalBlockEntity emptySameColumn = blockEntity(level, outOfColumnPos, TCInfusionPedestalBlockEntity.class);

        checks.add(new Check(
                "runtime_matrix_and_pedestal_block_entities_created",
                matrix != null && center != null && feather != null && crystal != null && emptySameColumn != null,
                "matrix=" + (matrix != null)
                        + ", center=" + (center != null)
                        + ", feather=" + (feather != null)
                        + ", crystal=" + (crystal != null)
        ));
        if (matrix == null || center == null || feather == null || crystal == null) {
            return;
        }

        center.setStoredForValidation(new ItemStack(TCItems.BAUBLE_RING.get()));
        feather.setStoredForValidation(new ItemStack(Items.FEATHER));
        crystal.setStoredForValidation(new ItemStack(TCItems.CRYSTAL_ESSENCE_AER.get()));

        TCInfusionMatrixBlockEntity.Snapshot snapshot = matrix.createSnapshot(new AspectList().add(Aspect.AIR, 50));
        checks.add(new Check(
                "runtime_matrix_detects_legacy_center_and_surrounding_pedestals",
                snapshot.hasCentralPedestal()
                        && snapshot.surroundingPedestalCount() == 3
                        && snapshot.componentCount() == 2,
                "surrounding=" + snapshot.surroundingPedestalCount() + ", components=" + snapshot.componentCount()
        ));

        TCInfusionValidationResult runtimeResult = matrix.validateAgainst(cloudRing, new AspectList().add(Aspect.AIR, 50));
        checks.add(new Check(
                "runtime_matrix_snapshot_matches_cloudring_recipe",
                runtimeResult.valid()
                        && runtimeResult.requiredComponentCount() == 2
                        && runtimeResult.suppliedComponentCount() == 2,
                "reason=" + runtimeResult.reason() + ", recipe=" + runtimeResult.recipeId()
        ));

        TCInfusionStartResult startResult = matrix.startCraftingForValidation(
                cloudRing,
                new AspectList().add(Aspect.AIR, 50),
                "AuditPlayer"
        );
        Optional<TCInfusionCraftingPlan> activePlan = matrix.activePlan();
        checks.add(new Check(
                "runtime_matrix_start_plan_cloudring",
                startResult.started()
                        && matrix.isCrafting()
                        && activePlan.isPresent()
                        && CLOUD_RING.equals(activePlan.get().recipeId()),
                "started=" + startResult.started() + ", reason=" + startResult.reason()
        ));
        checks.add(new Check(
                "runtime_matrix_start_plan_records_legacy_fields",
                activePlan.isPresent()
                        && "CLOUDRING".equals(activePlan.get().research())
                        && activePlan.get().instability() == 1
                        && activePlan.get().catalyst().is(TCItems.BAUBLE_RING.get())
                        && activePlan.get().components().size() == 2
                        && activePlan.get().requiredAspects().getAmount(Aspect.AIR) == 50
                        && activePlan.get().result().is(TCItems.CLOUD_RING.get())
                        && "AuditPlayer".equals(activePlan.get().playerName()),
                activePlan.map(plan -> "research=" + plan.research()
                                + ", instability=" + plan.instability()
                                + ", components=" + plan.components().size()
                                + ", aspects=" + plan.requiredAspectAmount())
                        .orElse("no active plan")
        ));
        checks.add(new Check(
                "runtime_matrix_start_plan_records_component_pedestal_positions",
                activePlan.isPresent()
                        && activePlan.get().componentPedestalPositions().size() == 2
                        && activePlan.get().componentPedestalPositions().contains(featherPos)
                        && activePlan.get().componentPedestalPositions().contains(crystalPos),
                activePlan.map(plan -> "positions=" + plan.componentPedestalPositions()).orElse("no active plan")
        ));
        checks.add(new Check(
                "runtime_matrix_active_plan_persists_through_nbt",
                activePlan.map(plan -> TCInfusionCraftingPlan.load(plan.save(server.registryAccess()), server.registryAccess()))
                        .map(loaded -> CLOUD_RING.equals(loaded.recipeId())
                                && loaded.components().size() == 2
                                && loaded.requiredAspects().getAmount(Aspect.AIR) == 50
                                && loaded.result().is(TCItems.CLOUD_RING.get()))
                        .orElse(false),
                activePlan.map(plan -> "recipe=" + plan.recipeId()).orElse("no active plan")
        ));
        TCInfusionStartResult secondStart = matrix.startCraftingForValidation(
                cloudRing,
                new AspectList().add(Aspect.AIR, 50),
                "AuditPlayer"
        );
        checks.add(new Check(
                "runtime_matrix_rejects_second_start_while_active",
                !secondStart.started() && "already_crafting".equals(secondStart.reason()),
                "reason=" + secondStart.reason()
        ));
        matrix.abortCrafting();
        checks.add(new Check(
                "runtime_matrix_abort_clears_start_plan",
                !matrix.isCrafting() && matrix.activePlan().isEmpty(),
                "active=" + matrix.isCrafting()
        ));

        level.setBlock(extraPos, TCBlocks.ARCANE_PEDESTAL.get().defaultBlockState(), 3);
        TCInfusionPedestalBlockEntity extra = blockEntity(level, extraPos, TCInfusionPedestalBlockEntity.class);
        if (extra != null) {
            extra.setStoredForValidation(new ItemStack(Items.STICK));
        }
        TCInfusionValidationResult extraResult = matrix.validateAgainst(cloudRing, new AspectList().add(Aspect.AIR, 50));
        checks.add(new Check(
                "runtime_matrix_extra_filled_pedestal_fails_one_to_one_match",
                !extraResult.valid() && "component_mismatch".equals(extraResult.reason()),
                "reason=" + extraResult.reason() + ", components=" + matrix.createSnapshot(new AspectList()).componentCount()
        ));

        level.setBlock(centerPos, Blocks.AIR.defaultBlockState(), 3);
        TCInfusionValidationResult missingCenterResult = matrix.validateAgainst(cloudRing, new AspectList().add(Aspect.AIR, 50));
        checks.add(new Check(
                "runtime_matrix_requires_central_pedestal_two_blocks_below",
                !missingCenterResult.valid() && "missing_central_pedestal".equals(missingCenterResult.reason()),
                "reason=" + missingCenterResult.reason()
        ));
    }

    private static void clearTestArea(ServerLevel level, BlockPos matrixPos) {
        for (int dx = -3; dx <= 3; dx++) {
            for (int dy = -3; dy <= 1; dy++) {
                for (int dz = -3; dz <= 3; dz++) {
                    level.setBlock(matrixPos.offset(dx, dy, dz), Blocks.AIR.defaultBlockState(), 3);
                }
            }
        }
    }

    private static <T> T blockEntity(ServerLevel level, BlockPos pos, Class<T> type) {
        Object blockEntity = level.getBlockEntity(pos);
        return type.isInstance(blockEntity) ? type.cast(blockEntity) : null;
    }

    public record Report(List<Check> checks, int infusionRecipeCount) {
        public int passed() {
            int passed = 0;
            for (Check check : checks) {
                if (check.passed()) {
                    passed++;
                }
            }
            return passed;
        }

        public int failed() {
            return checks.size() - passed();
        }
    }

    public record Check(String name, boolean passed, String notes) {
    }
}
